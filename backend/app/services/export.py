"""Export timetable views to Excel and PDF."""
import io
from typing import List, Dict, Any
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph


AVIU_PURPLE = "6B21A8"
AVIU_LIGHT = "F3E8FF"


def _cell_text(match):
    if not match:
        return ""
    code = match.get("module_code") or ""
    name = match.get("module_name") or ""
    room = match.get("room_code") or ""
    return code + "\n" + name + "\n" + room


def build_excel(title: str, cells: List[Dict[str, Any]], days: List[str] = None) -> bytes:
    if days is None:
        days = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday"]

    wb = Workbook()
    ws = wb.active
    ws.title = "Timetable"

    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=1 + len(days))
    title_cell = ws.cell(row=1, column=1, value=title)
    title_cell.font = Font(size=16, bold=True, color="FFFFFF")
    title_cell.fill = PatternFill(start_color=AVIU_PURPLE, end_color=AVIU_PURPLE, fill_type="solid")
    title_cell.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[1].height = 28

    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=1 + len(days))
    sub = ws.cell(row=2, column=1, value="Avance International University - Timetabling System")
    sub.font = Font(size=10, italic=True, color="666666")
    sub.alignment = Alignment(horizontal="center")

    header_row = 4
    headers = ["Time"] + days
    for col, h in enumerate(headers, start=1):
        c = ws.cell(row=header_row, column=col, value=h)
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill(start_color=AVIU_PURPLE, end_color=AVIU_PURPLE, fill_type="solid")
        c.alignment = Alignment(horizontal="center", vertical="center")

    time_slots = sorted({(c["start_time"], c["end_time"]) for c in cells})
    thin = Side(border_style="thin", color="CCCCCC")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)

    row = header_row + 1
    for start, end in time_slots:
        tc = ws.cell(row=row, column=1, value=start + "\n" + end)
        tc.font = Font(bold=True, size=9)
        tc.fill = PatternFill(start_color=AVIU_LIGHT, end_color=AVIU_LIGHT, fill_type="solid")
        tc.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        tc.border = border

        for day_idx, day in enumerate(days, start=2):
            match = None
            for c in cells:
                if c["day"] == day and c["start_time"] == start and c["end_time"] == end:
                    match = c
                    break
            text = _cell_text(match)
            cell = ws.cell(row=row, column=day_idx, value=text)
            cell.alignment = Alignment(horizontal="left", vertical="top", wrap_text=True)
            cell.border = border
            if match:
                cell.fill = PatternFill(start_color=AVIU_LIGHT, end_color=AVIU_LIGHT, fill_type="solid")

        ws.row_dimensions[row].height = 60
        row += 1

    ws.column_dimensions["A"].width = 12
    for col_idx in range(2, 2 + len(days)):
        ws.column_dimensions[chr(64 + col_idx)].width = 26

    buf = io.BytesIO()
    wb.save(buf)
    buf.seek(0)
    return buf.read()


def _pdf_cell_html(match):
    if not match:
        return ""
    code = match.get("module_code") or ""
    room = match.get("room_code") or ""
    return "<b>" + code + "</b><br/>" + room


def build_pdf(title: str, cells: List[Dict[str, Any]], days: List[str] = None) -> bytes:
    if days is None:
        days = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday"]

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=landscape(A4),
        topMargin=15 * mm,
        bottomMargin=15 * mm,
        leftMargin=15 * mm,
        rightMargin=15 * mm,
        title=title,
    )

    styles = getSampleStyleSheet()
    heading_style = ParagraphStyle(
        "AVIUHeading",
        parent=styles["Heading1"],
        textColor=colors.HexColor("#" + AVIU_PURPLE),
        fontSize=18,
        spaceAfter=6,
    )
    sub_style = ParagraphStyle(
        "AVIUSub",
        parent=styles["Normal"],
        textColor=colors.grey,
        fontSize=10,
        spaceAfter=14,
    )

    story = []
    story.append(Paragraph(title, heading_style))
    story.append(Paragraph("Avance International University - Generated by AVIU Timetabling System", sub_style))

    time_slots = sorted({(c["start_time"], c["end_time"]) for c in cells})

    data = [["Time"] + days]
    for start, end in time_slots:
        row = [start + "\n" + end]
        for day in days:
            match = None
            for c in cells:
                if c["day"] == day and c["start_time"] == start and c["end_time"] == end:
                    match = c
                    break
            row.append(_pdf_cell_html(match))
        data.append(row)

    tbl = Table(data, colWidths=[22 * mm] + [48 * mm] * len(days), repeatRows=1)
    tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#" + AVIU_PURPLE)),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 11),
        ("ALIGN", (0, 0), (-1, 0), "CENTER"),
        ("BACKGROUND", (0, 1), (0, -1), colors.HexColor("#" + AVIU_LIGHT)),
        ("FONTNAME", (0, 1), (0, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 1), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(tbl)

    doc.build(story)
    buf.seek(0)
    return buf.read()
